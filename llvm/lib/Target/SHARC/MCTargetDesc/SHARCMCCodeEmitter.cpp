#define DEBUG_TYPE "mccodeemitter"

using namespace llvm;

namespace {

class SHARCMCCodeEmitter : public MCCodeEmitter {
  const MCInstrInfo &MCII;
  MCContext &Ctx;

public:
  SHARCMCCodeEmitter(const MCInstrInfo &MCII, MCContext &Ctx)
      : MCII(MCII), Ctx(Ctx) {}

  void encodeInstruction(const MCInst &MI, SmallVectorImpl<char> &CB,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const override;

  // Generated by TableGen.
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;

  uint64_t getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;

  /// A nested computation, or 0 for none.
  uint64_t getNested(const MCInst &MI, unsigned OpNo, uint64_t Mask,
                     SmallVectorImpl<MCFixup> &Fixups,
                     const MCSubtargetInfo &STI) const;
  uint64_t getComputeOpValue(const MCInst &MI, unsigned OpNo,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const {
    return getNested(MI, OpNo, 0x7FFFFF, Fixups, STI);
  }
  uint64_t getShortComputeOpValue(const MCInst &MI, unsigned OpNo,
                                  SmallVectorImpl<MCFixup> &Fixups,
                                  const MCSubtargetInfo &STI) const {
    return getNested(MI, OpNo, 0xFFF, Fixups, STI);
  }
  uint64_t getShiftImmOpValue(const MCInst &MI, unsigned OpNo,
                              SmallVectorImpl<MCFixup> &Fixups,
                              const MCSubtargetInfo &STI) const {
    return getNested(MI, OpNo, 0x7FFFFF, Fixups, STI);
  }

  /// A 64-bit pair is encoded as its even register's number.
  uint64_t getDblRegOpValue(const MCInst &MI, unsigned OpNo,
                            SmallVectorImpl<MCFixup> &Fixups,
                            const MCSubtargetInfo &STI) const;

  uint64_t getImmOpValue(const MCInst &MI, unsigned OpNo,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const;
  uint64_t getPCRelOpValue(const MCInst &MI, unsigned OpNo,
                           SmallVectorImpl<MCFixup> &Fixups,
                           const MCSubtargetInfo &STI) const;
};

} // end anonymous namespace

MCCodeEmitter *llvm::createSHARCMCCodeEmitter(const MCInstrInfo &MCII,
                                              MCContext &Ctx) {
  return new SHARCMCCodeEmitter(MCII, Ctx);
}

void SHARCMCCodeEmitter::encodeInstruction(const MCInst &MI,
                                           SmallVectorImpl<char> &CB,
                                           SmallVectorImpl<MCFixup> &Fixups,
                                           const MCSubtargetInfo &STI) const {
  unsigned Width = MCII.get(MI.getOpcode()).getSize() * 8;
  uint64_t Bits = getBinaryCodeForInstr(MI, Fixups, STI);
  SHARC::writeParcels(Bits << (48 - Width), Width, CB);

  // Operands past the instruction's own come from the parser: hardware loop
  // positions (expressions), then optionally the 48-bit alternative.
  unsigned NumOps = SHARC::getOperandInfo(MI.getOpcode()).size();
  bool HasWide = MI.getNumOperands() > NumOps &&
                 MI.getOperand(MI.getNumOperands() - 1).isInst();
  for (unsigned I = NumOps; I < MI.getNumOperands(); ++I)
    if (MI.getOperand(I).isExpr())
      Fixups.push_back(MCFixup::create(
          0, MI.getOperand(I).getExpr(),
          HasWide ? SHARC::fixup_sharc_loop_end
                  : SHARC::fixup_sharc_loop_end_fixed));
}

uint64_t
SHARCMCCodeEmitter::getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                                      SmallVectorImpl<MCFixup> &Fixups,
                                      const MCSubtargetInfo &STI) const {
  if (MO.isReg())
    return Ctx.getRegisterInfo()->getEncodingValue(MO.getReg());
  if (MO.isImm())
    return MO.getImm();
  // The only symbolic field without its own encoder is the SHARC+ loop mode,
  // decided when the loop closes.
  Fixups.push_back(
      MCFixup::create(0, MO.getExpr(), SHARC::fixup_sharc_loop_mode));
  return 0;
}

uint64_t SHARCMCCodeEmitter::getNested(const MCInst &MI, unsigned OpNo,
                                       uint64_t Mask,
                                       SmallVectorImpl<MCFixup> &Fixups,
                                       const MCSubtargetInfo &STI) const {
  const MCOperand &MO = MI.getOperand(OpNo);
  if (MO.isImm())
    return MO.getImm() & Mask;
  return getBinaryCodeForInstr(*MO.getInst(), Fixups, STI) & Mask;
}

uint64_t
SHARCMCCodeEmitter::getDblRegOpValue(const MCInst &MI, unsigned OpNo,
                                     SmallVectorImpl<MCFixup> &Fixups,
                                     const MCSubtargetInfo &STI) const {
  const MCRegisterInfo &MRI = *Ctx.getRegisterInfo();
  MCRegister Even = MRI.getSubReg(MI.getOperand(OpNo).getReg(), SHARC::sub_even);
  return MRI.getEncodingValue(Even);
}

/// The fixup for a symbolic operand, from the field's width and kind and the
/// section mode. The parser only accepts symbols in fields listed here.
static std::optional<SHARC::Fixups> fixupFor(const MCInst &MI, unsigned OpNo,
                                            bool PCRel,
                                            const MCSubtargetInfo &STI) {
  bool VISA = STI.hasFeature(SHARC::FeatureVISASection);
  for (const SHARC::OperandInfo &O : SHARC::getOperandInfo(MI.getOpcode())) {
    if (O.Index != OpNo)
      continue;
    if (PCRel) {
      switch (O.Width) {
      case 24:
        return VISA ? SHARC::fixup_sharc_pcrel24_visa
                    : SHARC::fixup_sharc_pcrel24_isa;
      case 23:
        // On classic cores the loop offset is 24 bits (bit 23 is the SHARC+
        // loop mode).
        if (!STI.hasFeature(SHARC::FeatureSHARCPlus))
          return VISA ? SHARC::fixup_sharc_pcrel24_visa
                      : SHARC::fixup_sharc_pcrel24_isa;
        return VISA ? SHARC::fixup_sharc_pcrel23_visa
                    : SHARC::fixup_sharc_pcrel23_isa;
      case 6:
        return VISA ? SHARC::fixup_sharc_pcrel6_visa
                    : SHARC::fixup_sharc_pcrel6_isa;
      default:
        return std::nullopt;
      }
    }
    if (O.Width == 24 && O.Kind == SHARC::OpKind::Addr)
      return VISA ? SHARC::fixup_sharc_addr24_visa
                  : SHARC::fixup_sharc_addr24_isa;
    if (O.Width == 32)
      return SHARC::fixup_sharc_addr32;
    return std::nullopt;
  }
  return std::nullopt;
}

uint64_t SHARCMCCodeEmitter::getImmOpValue(const MCInst &MI, unsigned OpNo,
                                           SmallVectorImpl<MCFixup> &Fixups,
                                           const MCSubtargetInfo &STI) const {
  const MCOperand &MO = MI.getOperand(OpNo);
  if (MO.isImm())
    return MO.getImm();
  std::optional<SHARC::Fixups> Kind = fixupFor(MI, OpNo, false, STI);
  if (!Kind) {
    Ctx.reportError(MI.getLoc(), "this field cannot hold a symbol");
    return 0;
  }
  Fixups.push_back(MCFixup::create(0, MO.getExpr(), *Kind));
  return 0;
}

uint64_t
SHARCMCCodeEmitter::getPCRelOpValue(const MCInst &MI, unsigned OpNo,
                                    SmallVectorImpl<MCFixup> &Fixups,
                                    const MCSubtargetInfo &STI) const {
  const MCOperand &MO = MI.getOperand(OpNo);
  if (MO.isImm())
    return MO.getImm();
  std::optional<SHARC::Fixups> Kind = fixupFor(MI, OpNo, true, STI);
  if (!Kind) {
    Ctx.reportError(MI.getLoc(), "this field cannot hold a symbol");
    return 0;
  }
  Fixups.push_back(MCFixup::create(0, MO.getExpr(), *Kind, /*PCRel=*/true));
  return 0;
}

