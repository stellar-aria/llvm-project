#include "SHARCMCTargetDesc.h"
#include "SHARCParcels.h"
#include "llvm/MC/MCCodeEmitter.h"
#include "llvm/MC/MCContext.h"
#include "llvm/MC/MCExpr.h"
#include "llvm/MC/MCFixup.h"
#include "llvm/MC/MCInst.h"
#include "llvm/MC/MCInstrInfo.h"
#include "llvm/MC/MCRegisterInfo.h"
#include "llvm/MC/MCSubtargetInfo.h"

#define DEBUG_TYPE "mccodeemitter"

using namespace llvm;

namespace {

class SHARCMCCodeEmitter : public MCCodeEmitter {
  const MCInstrInfo &MCII;
  MCContext &Ctx;

public:
  SHARCMCCodeEmitter(const MCInstrInfo &MCII, MCContext &Ctx)
      : MCII(MCII), Ctx(Ctx) {}

  void encodeInstruction(const MCInst &MI, SmallVectorImpl<char> &CB,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const override;

  // Generated by TableGen.
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;

  uint64_t getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;

  /// A nested computation, or 0 for none.
  uint64_t getNested(const MCInst &MI, unsigned OpNo, uint64_t Mask,
                     SmallVectorImpl<MCFixup> &Fixups,
                     const MCSubtargetInfo &STI) const;
  uint64_t getComputeOpValue(const MCInst &MI, unsigned OpNo,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const {
    return getNested(MI, OpNo, 0x7FFFFF, Fixups, STI);
  }
  uint64_t getShortComputeOpValue(const MCInst &MI, unsigned OpNo,
                                  SmallVectorImpl<MCFixup> &Fixups,
                                  const MCSubtargetInfo &STI) const {
    return getNested(MI, OpNo, 0xFFF, Fixups, STI);
  }
  uint64_t getShiftImmOpValue(const MCInst &MI, unsigned OpNo,
                              SmallVectorImpl<MCFixup> &Fixups,
                              const MCSubtargetInfo &STI) const {
    return getNested(MI, OpNo, 0x7FFFFF, Fixups, STI);
  }

  /// A 64-bit pair is encoded as its even register's number.
  uint64_t getDblRegOpValue(const MCInst &MI, unsigned OpNo,
                            SmallVectorImpl<MCFixup> &Fixups,
                            const MCSubtargetInfo &STI) const;

  uint64_t getImmOpValue(const MCInst &MI, unsigned OpNo,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const;
  uint64_t getPCRelOpValue(const MCInst &MI, unsigned OpNo,
                           SmallVectorImpl<MCFixup> &Fixups,
                           const MCSubtargetInfo &STI) const;
};

} // end anonymous namespace

MCCodeEmitter *llvm::createSHARCMCCodeEmitter(const MCInstrInfo &MCII,
                                              MCContext &Ctx) {
  return new SHARCMCCodeEmitter(MCII, Ctx);
}

void SHARCMCCodeEmitter::encodeInstruction(const MCInst &MI,
                                           SmallVectorImpl<char> &CB,
                                           SmallVectorImpl<MCFixup> &Fixups,
                                           const MCSubtargetInfo &STI) const {
  unsigned Width = MCII.get(MI.getOpcode()).getSize() * 8;
  uint64_t Bits = getBinaryCodeForInstr(MI, Fixups, STI);
  SHARC::writeParcels(Bits << (48 - Width), Width, CB);
}

uint64_t
SHARCMCCodeEmitter::getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                                      SmallVectorImpl<MCFixup> &Fixups,
                                      const MCSubtargetInfo &STI) const {
  if (MO.isReg())
    return Ctx.getRegisterInfo()->getEncodingValue(MO.getReg());
  if (MO.isImm())
    return MO.getImm();
  llvm_unreachable("unexpected operand kind");
}

uint64_t SHARCMCCodeEmitter::getNested(const MCInst &MI, unsigned OpNo,
                                       uint64_t Mask,
                                       SmallVectorImpl<MCFixup> &Fixups,
                                       const MCSubtargetInfo &STI) const {
  const MCOperand &MO = MI.getOperand(OpNo);
  if (MO.isImm())
    return MO.getImm() & Mask;
  return getBinaryCodeForInstr(*MO.getInst(), Fixups, STI) & Mask;
}

uint64_t
SHARCMCCodeEmitter::getDblRegOpValue(const MCInst &MI, unsigned OpNo,
                                     SmallVectorImpl<MCFixup> &Fixups,
                                     const MCSubtargetInfo &STI) const {
  const MCRegisterInfo &MRI = *Ctx.getRegisterInfo();
  MCRegister Even = MRI.getSubReg(MI.getOperand(OpNo).getReg(), SHARC::sub_even);
  return MRI.getEncodingValue(Even);
}

uint64_t SHARCMCCodeEmitter::getImmOpValue(const MCInst &MI, unsigned OpNo,
                                           SmallVectorImpl<MCFixup> &Fixups,
                                           const MCSubtargetInfo &STI) const {
  const MCOperand &MO = MI.getOperand(OpNo);
  if (MO.isImm())
    return MO.getImm();
  Ctx.reportError(SMLoc(), "symbolic operands are not supported yet");
  return 0;
}

uint64_t
SHARCMCCodeEmitter::getPCRelOpValue(const MCInst &MI, unsigned OpNo,
                                    SmallVectorImpl<MCFixup> &Fixups,
                                    const MCSubtargetInfo &STI) const {
  return getImmOpValue(MI, OpNo, Fixups, STI);
}

