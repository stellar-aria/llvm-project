# RUN: llvm-mc -triple=sharc -mcpu=adsp-2137x -show-encoding %s | FileCheck %s
# Expected encodings are from digiemu's llvm_vectors.py (the encoding tables)
# and match the disassembler tests.

nop;
# CHECK: NOP;  // encoding: [0x00,0x00,0x00,0x00,0x00,0x00]
idle;
# CHECK: IDLE;  // encoding: [0x80,0x00,0x00,0x00,0x00,0x00]
emuidle;
# CHECK: EMUIDLE;  // encoding: [0xc0,0x00,0x00,0x00,0x00,0x00]
r0 = r1 + r2;
# CHECK: R0 = R1 + R2;  // encoding: [0x3e,0x01,0x00,0x00,0x12,0x10]
IF EQ R0 = R1 + R2;
# CHECK: IF EQ R0 = R1 + R2;  // encoding: [0x00,0x01,0x00,0x00,0x12,0x10]
if not ac f3 = f5 + f9;
# CHECK: IF NOT AC F3 = F5 + F9;  // encoding: [0x26,0x01,0x08,0x00,0x59,0x13]
R0 = 0x12345678;
# CHECK: R0 = 0x12345678;  // encoding: [0x00,0x0f,0x34,0x12,0x78,0x56]
i0 = 0x12345678;
# CHECK: I0 = 0x12345678;  // encoding: [0x10,0x0f,0x34,0x12,0x78,0x56]
// C-style comments are accepted.
/* So are block comments. */ R0 = R1 + R2;
# CHECK: R0 = R1 + R2;  // encoding: [0x3e,0x01,0x00,0x00,0x12,0x10]
R7 = BSET R6 BY R0, DM(I0,M3) = R5, PM(I11,M15) = R4;
# CHECK: R7 = BSET R6 BY R0, DM(I0, M3) = R5, PM(I11, M15) = R4;  // encoding: [0xea,0x30,0x2c,0xfa,0x60,0x07]
